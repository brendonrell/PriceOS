/*
 * lib/color/vocabulary — the Colorpedia's named-colour vocabulary.
 *
 * A FIXED, baked-in dictionary of real colour names with real hex values. It is
 * DATA, not generation: nothing here is produced at runtime, so the Colorpedia
 * cannot hallucinate a name, a number, or a story in front of a user (Brendon,
 * 2026-08-01).
 *
 * Any arbitrary colour — a hex sampled off a piece of art, a project's custom
 * colorway — snaps to its nearest neighbour in here by perceptual distance
 * (CIEDE2000). The panel always says WHICH named colour it matched and how far
 * away it is, so a snapped colour never pretends the story is its own.
 *
 * `note` carries the history, and it is only present where a colour genuinely
 * has one. A name with no note shows no note — an empty line beats an invented
 * one.
 */

export interface NamedColor {
    name: string;
    hex: string;
    /** Where the name comes from — the shelf it sits on. */
    origin: 'CSS' | 'Pigment' | 'Dye' | 'Heritage' | 'Nature' | 'Metal' | 'Modern';
    /** The colour's story. Absent when there isn't a real one to tell. */
    note?: string;
    /** Extra search terms — alternate spellings, systems, nicknames. */
    alt?: string[];
}

