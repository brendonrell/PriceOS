/** The whole vocabulary, in one list. Deduped by name at build time. */
export const NAMED_COLORS: NamedColor[] = (() => {
    const seen = new Set<string>();
    const out: NamedColor[] = [];
    for (const c of [...CSS_COLORS, ...PIGMENTS, ...DYES, ...HERITAGE, ...NATURE, ...METALS, ...MODERN, ...COVERAGE]) {
        const key = c.name.toLowerCase();
        if (seen.has(key)) continue;
        seen.add(key);
        out.push(c);
    }
    return out;
})();
